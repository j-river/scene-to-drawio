import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtemp, mkdir, readFile, writeFile, rm, copyFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
const root = process.cwd(), npm = process.env.npm_execpath;
assert.ok(npm, 'Run this through npm run test:package.');
const run = (args, cwd = root) => execFileSync(process.execPath, args, { cwd, encoding: 'utf8', windowsHide: true, timeout: 120_000 });
const npmRun = (args, cwd) => run([npm, ...args], cwd);
npmRun(['run', 'build']);
await mkdir('.artifacts', { recursive: true });
const [pack] = JSON.parse(npmRun(['pack', '--ignore-scripts', '--json', '--pack-destination', '.artifacts']));
const expected = ['CHANGELOG.md', 'LICENSE', 'README.md', 'dist/browser.js', 'dist/cli.js', 'dist/index.cjs', 'dist/index.d.cts', 'dist/index.d.ts', 'dist/index.js', 'package.json'].sort();
assert.deepEqual(pack.files.map(f => f.path).sort(), expected);
assert.ok(pack.unpackedSize < 300_000);
await writeFile('.artifacts/package-report.json', `${JSON.stringify(pack, null, 2)}\n`);
const dir = await mkdtemp(join(tmpdir(), 'drawio-package-'));
try {
  await writeFile(join(dir, 'package.json'), '{"name":"drawio-package-check","version":"1.0.0","type":"module","private":true}');
  const tarball = join(dir, pack.filename);
  await copyFile(resolve('.artifacts', pack.filename), tarball);
  npmRun(['install', tarball, '--offline', '--ignore-scripts', '--no-audit', '--no-fund', '--package-lock=false'], dir);
  await copyFile(resolve('examples/scene.json'), join(dir, 'scene.json'));
  await writeFile(join(dir, 'check.mjs'), `import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {toDrawioXml,validateScene} from 'scene-to-drawio';
import {toDrawioXml as browser} from 'scene-to-drawio/browser';
const scene=JSON.parse(readFileSync('scene.json','utf8'));
assert.equal(validateScene(scene).nodes.length,3);
assert.ok(toDrawioXml(scene).includes('source="cell_input"'));
assert.equal(browser(scene),toDrawioXml(scene));
console.log('Installed ESM and browser exports passed');\n`);
  await writeFile(join(dir, 'check.cjs'), `const assert=require('node:assert/strict');
const {toDrawioXml}=require('scene-to-drawio');
assert.ok(toDrawioXml({width:1,height:1,nodes:[]}).startsWith('<mxfile'));
console.log('Installed CommonJS export passed');\n`);
  process.stdout.write(run(['check.mjs'], dir)); process.stdout.write(run(['check.cjs'], dir));
  const manifest = JSON.parse(await readFile(join(dir, 'node_modules/scene-to-drawio/package.json'), 'utf8'));
  const cli = join(dir, 'node_modules/scene-to-drawio', manifest.bin['scene-to-drawio']);
  assert.ok(run([cli, 'scene.json'], dir).startsWith('<mxfile'));
  assert.ok(run([cli, 'scene.json', '--model'], dir).startsWith('<mxGraphModel'));
  for (const name of ['import.mts', 'require.cts']) await copyFile(resolve('tests/types', name), join(dir, name));
  run([resolve('node_modules/typescript/bin/tsc'), '--strict', '--noEmit', '--target', 'ES2022', '--module', 'NodeNext', '--moduleResolution', 'NodeNext', '--types', 'node', '--typeRoots', resolve('node_modules/@types'), 'import.mts', 'require.cts'], dir);
  console.log(`Installed tarball passed: ${pack.files.length} files, ${pack.size} bytes packed, ${pack.unpackedSize} bytes unpacked.`);
} finally { await rm(dir, { recursive: true, force: true }); }
